using System.Security.Cryptography;
using System.Text;

namespace SignalGrid.Ampelum.Agent.CodeIntelligence;

/// <summary>Kind of code symbol extracted during indexing.</summary>
public enum SymbolKind { Class, Method, Function, Property, Interface, Struct, Enum, Record, Field, Event, Delegate }

/// <summary>A single extracted symbol with its location, signature, summary, and embedding.</summary>
public sealed record Symbol(
    string File,
    int LineStart,
    int LineEnd,
    SymbolKind Kind,
    string Name,
    string Signature,
    string? Summary,
    string ContentHash,
    byte[]? Embedding = null,
    DateTime IndexedAt = default) : IComparable<Symbol>
{
    public DateTime IndexedAt { get; init; } = IndexedAt == default ? DateTime.UtcNow : IndexedAt;

    /// <summary>Whether this symbol needs a summary generated by the background LLM.</summary>
    public bool NeedsSummary => Summary is null;

    /// <summary>Text used for embedding: prefers LLM summary, falls back to signature.</summary>
    public string EmbeddingText => Summary ?? $"{Name}: {Signature}";

    /// <summary>Number of source lines this symbol spans.</summary>
    public int LineCount => LineEnd - LineStart + 1;

    public int CompareTo(Symbol? other)
    {
        if (other is null) return 1;
        var fileCmp = string.Compare(File, other.File, StringComparison.OrdinalIgnoreCase);
        return fileCmp != 0 ? fileCmp : LineStart.CompareTo(other.LineStart);
    }

    /// <summary>Computes the SHA256 content hash for validation.</summary>
    public static string ComputeHash(string sourceCode, int lineStart, int lineEnd)
    {
        var lines = sourceCode.Split('\n');
        var body = string.Join('\n', lines.Skip(Math.Max(0, lineStart - 1)).Take(lineEnd - lineStart + 1));
        var bytes = SHA256.HashData(Encoding.UTF8.GetBytes(body));
        return Convert.ToHexStringLower(bytes);
    }

    /// <summary>Creates a new Symbol with an updated summary.</summary>
    public Symbol WithSummary(string? summary) => this with { Summary = summary };

    /// <summary>Creates a new Symbol with an updated embedding.</summary>
    public Symbol WithEmbedding(byte[]? embedding) => this with { Embedding = embedding };
}

/// <summary>Result of a symbol extraction pass on a single file.</summary>
public sealed record ExtractResult(string File, Symbol[] Symbols, string? Error, CodeGraphEdge[]? Edges = null);

/// <summary>Progress notification for background indexing, including ETA for footer display.</summary>
public sealed record IndexProgress(int Done, int Total, string CurrentFile = "", string Phase = "scanning", TimeSpan? Eta = null)
{
    public int PercentDone => Total == 0 ? 0 : (int)(Done * 100L / Total);

    /// <summary>Compact footer label: "idx 145/847 ~2m30s" or "idx ready".</summary>
    public string FooterLabel => Phase == "ready"
        ? "idx ready"
        : Eta is { } eta
            ? $"idx {Done}/{Total} ~{FormatEta(eta)}"
            : $"idx {Done}/{Total}";

    private static string FormatEta(TimeSpan t) =>
        t.TotalMinutes >= 1
            ? $"{(int)t.TotalMinutes}m{t.Seconds:D2}s"
            : $"{(int)t.TotalSeconds}s";
}

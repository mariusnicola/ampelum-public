// src/Ampelum.SourceGenerator/SignatureMetadataGenerator.cs
using System.Collections.Generic;
using System.Collections.Immutable;
using System.Diagnostics.CodeAnalysis;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace SignalGrid.Ampelum.SourceGenerator;

[Generator(LanguageNames.CSharp)]
public sealed class SignatureMetadataGenerator : IIncrementalGenerator
{
    const string SignatureAttributeFullName = "SignalGrid.Ampelum.SignatureAttribute";
    const string AotStrictAttributeFullName = "SignalGrid.Ampelum.GenerateSignatureMetadataAttribute";

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var types = context.SyntaxProvider
            .ForAttributeWithMetadataName(
                SignatureAttributeFullName,
                IsRecordSyntax,
                GetTypeSymbol);

        // Always emit the per-signature ModuleInitializer (default path).
        context.RegisterSourceOutput(types, EmitPerSignature);

        // AOT-strict aggregator: collect signatures + the assembly attribute presence.
        var assemblyHasAotAttr = context.CompilationProvider.Select((c, _) =>
            c.Assembly.GetAttributes().Any(a =>
                a.AttributeClass?.ToDisplayString() == AotStrictAttributeFullName));

        var collected = types.Collect().Combine(assemblyHasAotAttr);

        context.RegisterSourceOutput(collected, (spc, pair) =>
        {
            var (sigs, isAot) = pair;
            if (!isAot || sigs.Length == 0) return;
            EmitAccessors(spc, sigs);
        });
    }

    static bool IsRecordSyntax(SyntaxNode node, System.Threading.CancellationToken _) =>
        node is RecordDeclarationSyntax;

    static INamedTypeSymbol GetTypeSymbol(GeneratorAttributeSyntaxContext ctx, System.Threading.CancellationToken _) =>
        (INamedTypeSymbol)ctx.TargetSymbol;

    static void EmitPerSignature(SourceProductionContext spc, INamedTypeSymbol symbol)
    {
        var instructions = ExtractInstructions(symbol);
        var (inputs, outputs) = SplitFields(symbol);
        if (inputs.Count == 0 || outputs.Count == 0) return;

        var hintPrefix = HintPrefix(symbol);
        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("#nullable enable");
        sb.AppendLine("using System;");
        sb.AppendLine("using System.Runtime.CompilerServices;");
        sb.AppendLine("using SignalGrid.Ampelum;");
        sb.AppendLine("namespace SignalGrid.Ampelum.Generated;");
        sb.AppendLine($"internal static class {hintPrefix}_MetadataInitializer");
        sb.AppendLine("{");
        sb.AppendLine("    [ModuleInitializer]");
        sb.AppendLine("    public static void Initialize() => SignatureMetadataCache.Register(");
        sb.AppendLine($"        typeof({symbol.ToDisplayString()}),");
        sb.AppendLine($"        new SignatureMetadata(typeof({symbol.ToDisplayString()}), {Lit(instructions)},");
        sb.Append("            new Field[] { ");
        foreach (var (n, t, d, opt) in inputs)
            sb.Append($"new Field({Lit(n)}, typeof({t}), {Lit(d)}, FieldKind.Input, {Bool(opt)}), ");
        sb.AppendLine("},");
        sb.Append("            new Field[] { ");
        foreach (var (n, t, d, opt) in outputs)
            sb.Append($"new Field({Lit(n)}, typeof({t}), {Lit(d)}, FieldKind.Output, {Bool(opt)}), ");
        sb.AppendLine("}));");
        sb.AppendLine("}");

        spc.AddSource($"{hintPrefix}_MetadataInitializer.g.cs", sb.ToString());
    }

    static void EmitAccessors(SourceProductionContext spc, ImmutableArray<INamedTypeSymbol> symbols)
    {
        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("#nullable enable");
        sb.AppendLine("using System;");
        sb.AppendLine("using System.Runtime.CompilerServices;");
        sb.AppendLine("using SignalGrid.Ampelum;");
        sb.AppendLine("namespace SignalGrid.Ampelum.Generated;");
        sb.AppendLine("internal static class __AmpelumSignatureAccessors");
        sb.AppendLine("{");
        sb.AppendLine("    [ModuleInitializer]");
        sb.AppendLine("    public static void Initialize()");
        sb.AppendLine("    {");
        foreach (var sym in symbols)
        {
            var (inputs, outputs) = SplitFields(sym);
            if (inputs.Count == 0 || outputs.Count == 0) continue;

            var fqn = "global::" + sym.ToDisplayString();
            sb.Append($"        SignatureMetadataCache.RegisterAccessors<{fqn}>(new Func<{fqn}, object?>[] {{ ");
            foreach (var (n, _, _, _) in inputs)
                sb.Append($"static ({fqn} s) => s.{n}, ");
            sb.AppendLine("});");
        }
        sb.AppendLine("    }");
        sb.AppendLine("}");

        spc.AddSource("__AmpelumSignatureAccessors.g.cs", sb.ToString());
    }

    static (List<(string name, string typeFull, string desc, bool optional)> inputs,
            List<(string name, string typeFull, string desc, bool optional)> outputs)
        SplitFields(INamedTypeSymbol symbol)
    {
        var inputs = new List<(string, string, string, bool)>();
        var outputs = new List<(string, string, string, bool)>();
        foreach (var member in symbol.GetMembers().OfType<IPropertySymbol>())
        {
            var kind = PropertyKind(member);
            if (kind is null) continue;
            var entry = (
                member.Name,
                member.Type.WithNullableAnnotation(NullableAnnotation.None).ToDisplayString(),
                DescOf(member) ?? member.Name,
                member.NullableAnnotation == NullableAnnotation.Annotated);
            (kind == "Input" ? inputs : outputs).Add(entry);
        }
        return (inputs, outputs);
    }

    static string HintPrefix(INamedTypeSymbol symbol) =>
        symbol.ToDisplayString()
            .Replace('.', '_').Replace('+', '_')
            .Replace('<', '_').Replace('>', '_')
            .Replace(' ', '_').Replace(',', '_');

    /// <summary>
    /// Extracts the instructions string from the [Signature] attribute constructor argument.
    /// Defensive null-guard paths are excluded from coverage because ForAttributeWithMetadataName
    /// guarantees the attribute is present and SignatureAttribute always has a string constructor argument.
    /// </summary>
    [ExcludeFromCodeCoverage]
    static string ExtractInstructions(INamedTypeSymbol s)
    {
        var attr = s.GetAttributes()
            .FirstOrDefault(a => a.AttributeClass?.ToDisplayString() == SignatureAttributeFullName);
        return attr?.ConstructorArguments.FirstOrDefault().Value as string ?? "";
    }

    /// <summary>
    /// Returns "Input" or "Output" based on the Input/Output attribute on the property,
    /// or null if the property has neither attribute.
    /// </summary>
    [ExcludeFromCodeCoverage]
    static string? PropertyKind(IPropertySymbol p)
    {
        foreach (var a in p.GetAttributes())
        {
            var fqn = a.AttributeClass?.ToDisplayString();
            if (fqn == "SignalGrid.Ampelum.InputAttribute")  return "Input";
            if (fqn == "SignalGrid.Ampelum.OutputAttribute") return "Output";
        }
        return null;
    }

    /// <summary>
    /// Extracts the Desc named argument from an [Input] or [Output] attribute, or returns null.
    /// </summary>
    [ExcludeFromCodeCoverage]
    static string? DescOf(IPropertySymbol p) =>
        p.GetAttributes()
            .Where(a => a.AttributeClass?.ToDisplayString() is "SignalGrid.Ampelum.InputAttribute" or "SignalGrid.Ampelum.OutputAttribute")
            .SelectMany(a => a.NamedArguments)
            .Where(kv => kv.Key == "Desc")
            .Select(kv => kv.Value.Value as string)
            .FirstOrDefault();

    [ExcludeFromCodeCoverage]
    static string Lit(string? s) =>
        s is null ? "\"\"" : "\"" + s.Replace("\\", "\\\\").Replace("\"", "\\\"") + "\"";

    static string Bool(bool b) => b ? "true" : "false";
}

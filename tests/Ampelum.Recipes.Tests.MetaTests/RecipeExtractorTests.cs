using Ampelum.RecipeExtract;
using Shouldly;
using Xunit;

namespace Ampelum.Recipes.Tests.MetaTests;

public sealed class RecipeExtractorTests
{
    [Fact]
    public void Extracts_TaggedFencedCsharp_ToCompilableTestFile()
    {
        var tempIn = Path.Combine(Path.GetTempPath(), Guid.NewGuid().ToString("N"));
        var tempOut = Path.Combine(Path.GetTempPath(), Guid.NewGuid().ToString("N"));
        Directory.CreateDirectory(tempIn);
        try
        {
            File.WriteAllText(Path.Combine(tempIn, "r.md"),
                "# X\n\n```csharp\n// ampelum:recipe hello-world\nvar x = 1;\n```\n");
            var n = Program.Run(tempIn, tempOut);
            n.ShouldBe(1);
            var generated = Path.Combine(tempOut, "HelloWorld.g.cs");
            File.Exists(generated).ShouldBeTrue();
            var src = File.ReadAllText(generated);
            src.ShouldContain("[Fact]");
            src.ShouldContain("public sealed class HelloWorld");
            src.ShouldContain("var x = 1;");
            src.ShouldContain("// <auto-generated/>");
        }
        finally
        {
            Directory.Delete(tempIn, recursive: true);
            if (Directory.Exists(tempOut)) Directory.Delete(tempOut, recursive: true);
        }
    }

    [Fact]
    public void Extracts_IgnoresUntaggedBlocks()
    {
        var tempIn = Path.Combine(Path.GetTempPath(), Guid.NewGuid().ToString("N"));
        var tempOut = Path.Combine(Path.GetTempPath(), Guid.NewGuid().ToString("N"));
        Directory.CreateDirectory(tempIn);
        try
        {
            File.WriteAllText(Path.Combine(tempIn, "r.md"),
                "```csharp\nvar y = 2;\n```\n\n```csharp\n// ampelum:recipe alpha\nvar z = 3;\n```\n");
            var n = Program.Run(tempIn, tempOut);
            n.ShouldBe(1);
            File.Exists(Path.Combine(tempOut, "Alpha.g.cs")).ShouldBeTrue();
        }
        finally
        {
            Directory.Delete(tempIn, recursive: true);
            if (Directory.Exists(tempOut)) Directory.Delete(tempOut, recursive: true);
        }
    }

    [Fact]
    public void ExtractBlocks_HandlesMultipleSlugs()
    {
        var md = "```csharp\n// ampelum:recipe one\nA\n```\n```csharp\n// ampelum:recipe two\nB\n```\n";
        var blocks = Program.ExtractBlocks(md).ToArray();
        blocks.Length.ShouldBe(2);
        blocks[0].Slug.ShouldBe("one");
        blocks[1].Slug.ShouldBe("two");
    }

    [Fact]
    public void Run_MissingDir_ReturnsZero()
    {
        var n = Program.Run(Path.Combine(Path.GetTempPath(), Guid.NewGuid().ToString("N")), Path.GetTempPath());
        n.ShouldBe(0);
    }

    [Fact]
    public void Render_EmitsExpectedSkeleton()
    {
        var rendered = Program.Render("Foo", "var a=1;\n");
        rendered.ShouldContain("namespace Ampelum.Recipes.Tests.Generated;");
        rendered.ShouldContain("public sealed class Foo");
        rendered.ShouldContain("[Fact]");
        rendered.ShouldContain("var a=1;");
    }

    [Fact]
    public void Main_NoArgs_ReturnsOne()
    {
        Program.Main(System.Array.Empty<string>()).ShouldBe(1);
    }

    [Fact]
    public void Main_HappyPath_ReturnsZero()
    {
        var tempIn = Path.Combine(Path.GetTempPath(), Guid.NewGuid().ToString("N"));
        var tempOut = Path.Combine(Path.GetTempPath(), Guid.NewGuid().ToString("N"));
        Directory.CreateDirectory(tempIn);
        try
        {
            File.WriteAllText(Path.Combine(tempIn, "x.md"), "```csharp\n// ampelum:recipe k\nint k=0;\n```\n");
            Program.Main(new[] { tempIn, tempOut }).ShouldBe(0);
        }
        finally
        {
            Directory.Delete(tempIn, recursive: true);
            if (Directory.Exists(tempOut)) Directory.Delete(tempOut, recursive: true);
        }
    }
}
